#!/usr/bin/env python3
"""Generate visual Xacro/configs from Blender manifest; requires xacro/PyYAML.

Preserves calibration.yaml unless --reset-nominal is explicitly passed.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import yaml
import xacro

ROOT=Path(__file__).resolve().parents[2]
NS='http://www.ros.org/wiki/xacro'
ET.register_namespace('xacro',NS)
X=lambda name:'{'+NS+'}'+name


def generate(package,reset=False):
    manifest=json.loads((package/'config/mesh_export_r19.json').read_text())
    root=ET.Element('robot')
    macro=ET.SubElement(root,X('macro'),name='r19_visuals',params='link')
    for link,visuals in sorted(manifest['visuals'].items()):
        condition=ET.SubElement(macro,X('if'),value="${link == '"+link+"'}")
        for n,v in enumerate(visuals):
            visual=ET.SubElement(condition,'visual',name=f'{link}_visual_{n}')
            geometry=ET.SubElement(visual,'geometry')
            scale='1 1 1'
            if link in ['left_wheel_link','right_wheel_link']:
                scale="${wheel_radius / 0.033875} ${wheel_width / 0.029} ${wheel_radius / 0.033875}"
            ET.SubElement(geometry,'mesh',filename='package://roam_e_description/'+v['mesh'],scale=scale)
            material=ET.SubElement(visual,'material',name=f'r19_{link}_{n}')
            ET.SubElement(material,'color',rgba=' '.join(str(c) for c in v['rgba']))
    rigid=ET.SubElement(root,X('macro'),name='r19_rigid_links',params='')
    for link in sorted(manifest['visuals']):
        if link in ['left_wheel_link','right_wheel_link']:continue
        node=ET.SubElement(rigid,'link',name=link)
        ET.SubElement(node,X('r19_visuals'),link=link)
        if link!='base_link':ET.SubElement(rigid,X('fixed_frame'),child=link)
    ET.indent(root)
    (package/'urdf/r19_visuals.xacro').write_text(
        '<?xml version="1.0"?>\n<!-- Generated by tools/description/build_description.py; mesh units metres. -->\n'
        +ET.tostring(root,encoding='unicode')+'\n')
    nominal={'revision':'R19 nominal CAD; not measured sensor calibration','forward':manifest['forward'],
        'physical_wheels':{'radius':manifest['physical_wheel_radius_m'],
            'separation':manifest['physical_wheel_separation_m'],'width':.029},
        'effective_odometry':{'radius':manifest['effective_odometry_radius_m'],
            'separation':manifest['effective_odometry_separation_m'],
            'note':'Existing floor/turn-calibrated runtime values; not changed by this export.'},
        'frames':manifest['frames']}
    for name in ['left_wheel_link','right_wheel_link']:nominal['frames'].pop(name)
    header=('# Distances metres; rotations radians. CAD starting values, NOT measured calibration.\n'
        '# Copy this file, edit measured xyz/rpy, then launch with calibration_file:=/absolute/path.yaml.\n'
        '# Disable camera optical preview TF when OpenNI2 owns those frames.\n')
    content=header+yaml.safe_dump(nominal,sort_keys=False)
    (package/'config/calibration_nominal_r19.yaml').write_text(content)
    dest=package/'config/calibration.yaml'
    if reset or not dest.exists():dest.write_text(content)
    elif yaml.safe_load(dest.read_text())['forward']!=manifest['forward']:
        raise ValueError('Forward convention changed: explicitly reset nominal calibration or supply a matching file')
    geometry={'revision':'R19','mesh_units':'metres','forward':manifest['forward'],
        'wheel_radius':manifest['physical_wheel_radius_m'],'wheel_separation':manifest['physical_wheel_separation_m'],
        'navigation_footprint_candidate':{'points':manifest['navigation_footprint_candidate'],'padding':.01,
            'status':'Projected CAD hull; inspect real robot before replacing Nav2 footprint'},
        'calibration_file':'calibration.yaml','limits':manifest['limits']}
    (package/'config/geometry.yaml').write_text(yaml.safe_dump(geometry,sort_keys=False))
    urdf=xacro.process_file(str(package/'urdf/roam_e.urdf.xacro'),mappings={
        'calibration_file':str(dest),'include_camera_optical_frames':'true'})
    (package/'urdf/roam_e.urdf').write_text(urdf.toprettyxml(indent='  '))
    return manifest


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--package',type=Path,default=ROOT/'src/roam_e_description')
    p.add_argument('--reset-nominal',action='store_true')
    args=p.parse_args();generate(args.package.resolve(),args.reset_nominal)
    print('R19 description generated; calibration.yaml preserved unless explicitly reset.')
